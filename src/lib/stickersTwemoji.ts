/** Código del emoji como en los nombres de archivo de Twemoji (sin el selector FE0F cuando va solo). */
export function twemojiCode(emoji: string): string {
  const cps = Array.from(emoji).map((c) => c.codePointAt(0)!.toString(16))
  return (emoji.includes('‍') ? cps : cps.filter((c) => c !== 'fe0f')).join('-')
}
